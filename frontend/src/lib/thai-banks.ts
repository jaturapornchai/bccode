export function filterThaiBankPresets(query: string): ThaiBankPreset[] {
  const q = query.trim().toLowerCase();
  if (!q) return [...thaiBankPresets];
  return thaiBankPresets.filter(
    (item) =>
      item.code.toLowerCase().includes(q) ||
      item.botCode.toLowerCase().includes(q) ||
      item.nameTh.toLowerCase().includes(q) ||
      item.shortNameTh.toLowerCase().includes(q) ||
      item.nameEn.toLowerCase().includes(q),
  );
}

export function findThaiBankPreset(codeOrBotCode: string): ThaiBankPreset | undefined {
  const target = codeOrBotCode.trim().toLowerCase();
  if (!target) return undefined;
  return thaiBankPresets.find(
    (item) =>
      item.code.toLowerCase() === target ||
      item.botCode.toLowerCase() === target,
  );
}
