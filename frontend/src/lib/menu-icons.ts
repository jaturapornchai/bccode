export function menuIconKeyForRoute(route: string, category: MenuCategory): MenuIconKey {
  return ROUTE_ICON_KEYS[route] ?? CATEGORY_ICON_KEYS[category] ?? "grid";
}

export function hasExplicitMenuIcon(route: string): boolean {
  return Object.prototype.hasOwnProperty.call(ROUTE_ICON_KEYS, route);
}
