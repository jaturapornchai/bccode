type IChequeReturnHttp interface{}

type ChequeReturnHttp struct {
	ms  *microservice.Microservice
	cfg config.IConfig
	svc services.IChequeReturnHttpService
}

func NewChequeReturnHttp(ms *microservice.Microservice, cfg config.IConfig) ChequeReturnHttp {
	pst := ms.MongoPersister(cfg.MongoPersisterConfig())
	cache := ms.Cacher(cfg.CacherConfig())
	producer := ms.Producer(cfg.MQConfig())

	repo := repositories.NewChequeReturnRepository(pst)
	repoMq := repositories.NewChequeReturnMessageQueueRepository(producer)

	transRepo := trancache.NewCacheRepository(cache)
	masterSyncCacheRepo := mastersync.NewMasterSyncCacheRepository(cache)
	svc := services.NewChequeReturnHttpService(repo, transRepo, repoMq, masterSyncCacheRepo)

	return ChequeReturnHttp{
		ms:  ms,
		cfg: cfg,
		svc: svc,
	}
}

func (h ChequeReturnHttp) RegisterHttp() {

	h.ms.POST("/transaction/chequereceive/chequereturn/bulk", h.SaveBulk)

	h.ms.GET("/transaction/chequereceive/chequereturn", h.SearchChequeReturnPage)
	h.ms.GET("/transaction/chequereceive/chequereturn/list", h.SearchChequeReturnStep)
	h.ms.POST("/transaction/chequereceive/chequereturn", h.CreateChequeReturn)
	h.ms.GET("/transaction/chequereceive/chequereturn/:id", h.InfoChequeReturn)
	h.ms.GET("/transaction/chequereceive/chequereturn/code/:code", h.InfoChequeReturnByCode)
	h.ms.PUT("/transaction/chequereceive/chequereturn/:id", h.UpdateChequeReturn)
	h.ms.DELETE("/transaction/chequereceive/chequereturn/:id", h.DeleteChequeReturn)
	h.ms.DELETE("/transaction/chequereceive/chequereturn", h.DeleteChequeReturnByGUIDs)
}

