type IAdvancePaymentHttp interface{}

type AdvancePaymentHttp struct {
	ms  *microservice.Microservice
	cfg config.IConfig
	svc services.IAdvancePaymentHttpService
}

func NewAdvancePaymentHttp(ms *microservice.Microservice, cfg config.IConfig) AdvancePaymentHttp {
	pst := ms.MongoPersister(cfg.MongoPersisterConfig())
	cache := ms.Cacher(cfg.CacherConfig())
	producer := ms.Producer(cfg.MQConfig())

	repo := repositories.NewAdvancePaymentRepository(pst)
	repoMq := repositories.NewAdvancePaymentMessageQueueRepository(producer)

	transRepo := trancache.NewCacheRepository(cache)
	masterSyncCacheRepo := mastersync.NewMasterSyncCacheRepository(cache)
	svc := services.NewAdvancePaymentHttpService(repo, transRepo, repoMq, masterSyncCacheRepo)

	return AdvancePaymentHttp{
		ms:  ms,
		cfg: cfg,
		svc: svc,
	}
}

func (h AdvancePaymentHttp) RegisterHttp() {

	h.ms.POST("/transaction/advancepayment/bulk", h.SaveBulk)

	h.ms.GET("/transaction/advancepayment", h.SearchAdvancePaymentPage)
	h.ms.GET("/transaction/advancepayment/list", h.SearchAdvancePaymentStep)
	h.ms.POST("/transaction/advancepayment", h.CreateAdvancePayment)
	h.ms.GET("/transaction/advancepayment/:id", h.InfoAdvancePayment)
	h.ms.GET("/transaction/advancepayment/code/:code", h.InfoAdvancePaymentByCode)
	h.ms.PUT("/transaction/advancepayment/:id", h.UpdateAdvancePayment)
	h.ms.DELETE("/transaction/advancepayment/:id", h.DeleteAdvancePayment)
	h.ms.DELETE("/transaction/advancepayment", h.DeleteAdvancePaymentByGUIDs)
}

