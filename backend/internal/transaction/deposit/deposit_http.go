type IDepositHttp interface{}

type DepositHttp struct {
	ms  *microservice.Microservice
	cfg config.IConfig
	svc services.IDepositHttpService
}

func NewDepositHttp(ms *microservice.Microservice, cfg config.IConfig) DepositHttp {
	pst := ms.MongoPersister(cfg.MongoPersisterConfig())
	cache := ms.Cacher(cfg.CacherConfig())
	producer := ms.Producer(cfg.MQConfig())

	repo := repositories.NewDepositRepository(pst)
	repoMq := repositories.NewDepositMessageQueueRepository(producer)

	transRepo := trancache.NewCacheRepository(cache)
	masterSyncCacheRepo := mastersync.NewMasterSyncCacheRepository(cache)
	svc := services.NewDepositHttpService(repo, transRepo, repoMq, masterSyncCacheRepo)

	return DepositHttp{
		ms:  ms,
		cfg: cfg,
		svc: svc,
	}
}

func (h DepositHttp) RegisterHttp() {

	h.ms.POST("/transaction/deposit/bulk", h.SaveBulk)

	h.ms.GET("/transaction/deposit", h.SearchDepositPage)
	h.ms.GET("/transaction/deposit/list", h.SearchDepositStep)
	h.ms.POST("/transaction/deposit", h.CreateDeposit)
	h.ms.GET("/transaction/deposit/:id", h.InfoDeposit)
	h.ms.GET("/transaction/deposit/code/:code", h.InfoDepositByCode)
	h.ms.PUT("/transaction/deposit/:id", h.UpdateDeposit)
	h.ms.DELETE("/transaction/deposit/:id", h.DeleteDeposit)
	h.ms.DELETE("/transaction/deposit", h.DeleteDepositByGUIDs)
}

// Create Deposit godoc
// @Description Create Deposit
// @Tags		Deposit
// @Param		Deposit  body      models.Deposit  true  "Deposit"
// @Accept 		json
// @Success		201	{object}	common.ResponseSuccessWithID
// @Failure		401 {object}	common.AuthResponseFailed
// @Security     AccessToken
// @Router /transaction/deposit [post]
func (h DepositHttp) CreateDeposit(ctx microservice.IContext) error {
	authUsername := ctx.UserInfo().Username
	shopID := ctx.UserInfo().ShopID
	input := ctx.ReadInput()

	docReq := &models.Deposit{}
	err := json.Unmarshal([]byte(input), &docReq)

	if err != nil {
		ctx.ResponseError(400, err.Error())
		return err
	}

	if err = ctx.Validate(docReq); err != nil {
		ctx.ResponseError(400, err.Error())
		return err
	}

	idx, docNo, err := h.svc.CreateDeposit(shopID, authUsername, *docReq)

	if err != nil {
		ctx.ResponseError(http.StatusBadRequest, err.Error())
		return err
	}

	ctx.Response(http.StatusCreated, common.ApiResponse{
		Success: true,
		ID:      idx,
		Data:    docNo,
	})
	return nil
}

