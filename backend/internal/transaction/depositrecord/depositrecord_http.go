type IDepositRecordHttp interface{}

type DepositRecordHttp struct {
	ms  *microservice.Microservice
	cfg config.IConfig
	svc services.IDepositRecordHttpService
}

func NewDepositRecordHttp(ms *microservice.Microservice, cfg config.IConfig) DepositRecordHttp {
	pst := ms.MongoPersister(cfg.MongoPersisterConfig())
	cache := ms.Cacher(cfg.CacherConfig())
	producer := ms.Producer(cfg.MQConfig())

	repo := repositories.NewDepositRecordRepository(pst)
	repoMq := repositories.NewDepositRecordMessageQueueRepository(producer)

	transRepo := trancache.NewCacheRepository(cache)
	masterSyncCacheRepo := mastersync.NewMasterSyncCacheRepository(cache)
	svc := services.NewDepositRecordHttpService(repo, transRepo, repoMq, masterSyncCacheRepo)

	return DepositRecordHttp{
		ms:  ms,
		cfg: cfg,
		svc: svc,
	}
}

func (h DepositRecordHttp) RegisterHttp() {

	h.ms.POST("/transaction/bank/depositrecord/bulk", h.SaveBulk)

	h.ms.GET("/transaction/bank/depositrecord", h.SearchDepositRecordPage)
	h.ms.GET("/transaction/bank/depositrecord/list", h.SearchDepositRecordStep)
	h.ms.POST("/transaction/bank/depositrecord", h.CreateDepositRecord)
	h.ms.GET("/transaction/bank/depositrecord/:id", h.InfoDepositRecord)
	h.ms.GET("/transaction/bank/depositrecord/code/:code", h.InfoDepositRecordByCode)
	h.ms.PUT("/transaction/bank/depositrecord/:id", h.UpdateDepositRecord)
	h.ms.DELETE("/transaction/bank/depositrecord/:id", h.DeleteDepositRecord)
	h.ms.DELETE("/transaction/bank/depositrecord", h.DeleteDepositRecordByGUIDs)
}

