type IChequePassHttp interface{}

type ChequePassHttp struct {
	ms  *microservice.Microservice
	cfg config.IConfig
	svc services.IChequePassHttpService
}

func NewChequePassHttp(ms *microservice.Microservice, cfg config.IConfig) ChequePassHttp {
	pst := ms.MongoPersister(cfg.MongoPersisterConfig())
	cache := ms.Cacher(cfg.CacherConfig())
	producer := ms.Producer(cfg.MQConfig())

	repo := repositories.NewChequePassRepository(pst)
	repoMq := repositories.NewChequePassMessageQueueRepository(producer)

	transRepo := trancache.NewCacheRepository(cache)
	masterSyncCacheRepo := mastersync.NewMasterSyncCacheRepository(cache)
	svc := services.NewChequePassHttpService(repo, transRepo, repoMq, masterSyncCacheRepo)

	return ChequePassHttp{
		ms:  ms,
		cfg: cfg,
		svc: svc,
	}
}

func (h ChequePassHttp) RegisterHttp() {

	h.ms.POST("/transaction/chequereceive/chequepass/bulk", h.SaveBulk)

	h.ms.GET("/transaction/chequereceive/chequepass", h.SearchChequePassPage)
	h.ms.GET("/transaction/chequereceive/chequepass/list", h.SearchChequePassStep)
	h.ms.POST("/transaction/chequereceive/chequepass", h.CreateChequePass)
	h.ms.GET("/transaction/chequereceive/chequepass/:id", h.InfoChequePass)
	h.ms.GET("/transaction/chequereceive/chequepass/code/:code", h.InfoChequePassByCode)
	h.ms.PUT("/transaction/chequereceive/chequepass/:id", h.UpdateChequePass)
	h.ms.DELETE("/transaction/chequereceive/chequepass/:id", h.DeleteChequePass)
	h.ms.DELETE("/transaction/chequereceive/chequepass", h.DeleteChequePassByGUIDs)
}

