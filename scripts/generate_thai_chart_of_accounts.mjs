// Generate SQL Script for PostgreSQL
function deterministicId(holding, company, code) {
  const hash = crypto.createHash('md5').update(`${holding}:${company}:${code}`).digest('hex');
  return `${hash.slice(0, 8)}-${hash.slice(8, 12)}-4${hash.slice(13, 16)}-a${hash.slice(17, 20)}-${hash.slice(20, 32)}`;
}

function buildSqlForCompany(holding, company) {
  let sql = `\n-- Accounts for Holding: ${holding}, Company: ${company}\n`;
  for (const a of accounts) {
    const id = deterministicId(holding, company, a.accountcode);
    const payload = JSON.stringify({
      id: id,
      holdingcode: holding,
      businesscode: company,
      version: 1,
      createdat: '2026-09-20T00:00:00.000Z',
      createdby: 'system',
      updatedat: '2026-09-20T00:00:00.000Z',
      updatedby: 'system',
      isdeleted: false,
      accountcode: a.accountcode,
      names: [
        { code: 'th', name: a.nameTh },
        { code: 'en', name: a.nameEn },
      ],
      accounttype: a.accounttype,
      parentaccountcode: a.parentaccountcode,
      normalbalance: a.normalbalance,
      allowposting: a.allowposting,
      isactive: true,
      accountgroup: a.accountgroup,
      iscash: a.iscash,
      level: a.level,
    }).replace(/'/g, "''");

    sql += `INSERT INTO gl_records(company, kind, id, code, version, payload)\n`;
    sql += `VALUES ('${company}', 'accounts', '${id}', '${a.accountcode}', 1, '${payload}'::jsonb)\n`;
    sql += `ON CONFLICT (company, kind, id) DO UPDATE SET\n`;
    sql += `  code = EXCLUDED.code,\n`;
    sql += `  version = gl_records.version + 1,\n`;
    sql += `  payload = EXCLUDED.payload;\n\n`;
  }
  return sql;
}

