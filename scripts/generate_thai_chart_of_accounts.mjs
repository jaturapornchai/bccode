function generateHoldingSql(holding, companies) {
  let sql = `\n-- ============================================================================\n`;
  sql += `-- Holding: ${holding}\n`;
  sql += `-- ============================================================================\n`;

  for (const cmp of companies) {
    // 1. Fiscal year
    const fyId = deterministicId(holding, cmp, '2569');
    const fyPayload = JSON.stringify({
      id: fyId,
      code: '2569',
      kind: 'fiscal-years',
      startdate: '2026-01-01',
      enddate: '2026-12-31',
      scale: 2,
      profitlossaccount: '3222',
      retainedearningsaccount: '3221',
      closed: false,
      isactive: true,
      version: 1,
      createdat: '2026-09-20T00:00:00.000Z',
      createdby: 'system',
      updatedat: '2026-09-20T00:00:00.000Z',
      updatedby: 'system',
      isdeleted: false,
      holdingcode: holding,
      businesscode: cmp,
    }).replace(/'/g, "''");
    sql += `INSERT INTO gl_records(company, kind, id, code, version, payload)\n`;
    sql += `VALUES ('${cmp}', 'fiscal-years', '${fyId}', '2569', 1, '${fyPayload}'::jsonb)\n`;
    sql += `ON CONFLICT (company, kind, id) DO NOTHING;\n\n`;

    // 2. Journal Books
    for (const b of books) {
      const bId = deterministicId(holding, cmp, b.code);
      const bPayload = JSON.stringify({
        id: bId,
        code: b.code,
        kind: 'journal-books',
        name: b.name,
        isactive: true,
        version: 1,
        createdat: '2026-09-20T00:00:00.000Z',
        createdby: 'system',
        updatedat: '2026-09-20T00:00:00.000Z',
        updatedby: 'system',
        isdeleted: false,
        holdingcode: holding,
        businesscode: cmp,
      }).replace(/'/g, "''");
      sql += `INSERT INTO gl_records(company, kind, id, code, version, payload)\n`;
      sql += `VALUES ('${cmp}', 'journal-books', '${bId}', '${b.code}', 1, '${bPayload}'::jsonb)\n`;
      sql += `ON CONFLICT (company, kind, id) DO NOTHING;\n\n`;
    }

    // 3. Account Groups
    for (const g of groups) {
      const gid = deterministicId(holding, cmp, g.code);
      const gPayload = JSON.stringify({
        id: gid,
        code: g.code,
        kind: 'account-groups',
        name: g.name,
        amount: '0',
        locked: false,
        version: 1,
        isactive: true,
        createdat: '2026-09-20T00:00:00.000Z',
        createdby: 'system',
        isdeleted: false,
        updatedat: '2026-09-20T00:00:00.000Z',
        updatedby: 'system',
        holdingcode: holding,
        businesscode: cmp,
      }).replace(/'/g, "''");

      sql += `INSERT INTO gl_records(company, kind, id, code, version, payload)\n`;
      sql += `VALUES ('${cmp}', 'account-groups', '${gid}', '${g.code}', 1, '${gPayload}'::jsonb)\n`;
      sql += `ON CONFLICT (company, kind, id) DO UPDATE SET payload = EXCLUDED.payload;\n\n`;
    }

    // 4. Accounts
    sql += buildSqlForCompany(holding, cmp);
  }
  return sql;
}

function generateFullSqlForHolding(holding, companies) {
  let fullSql = `-- ============================================================================\n`;
  fullSql += `-- Thai Standard Chart of Accounts for Holding: ${holding} (3 Levels, ${accounts.length} Accounts)\n`;
  fullSql += `-- Compatible with Thai Accounting Standards (TFRS for NPAEs / DBD / RD)\n`;
  fullSql += `-- Wrapped in transaction for ACID safety\n`;
  fullSql += `-- ============================================================================\n\n`;
  fullSql += `BEGIN;\n\n`;
  fullSql += generateHoldingSql(holding, companies);
  fullSql += `COMMIT;\n`;
  return fullSql;
}

